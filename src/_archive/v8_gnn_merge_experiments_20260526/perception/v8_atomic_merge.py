"""Build a v8 atomic-fragment merge view from MinerU middle evidence.

This module is deliberately separate from the default v8 reconstruction path.
It does not mutate v8 JSON, does not build PyG tensors, and does not expose any
ground-truth labels as model inputs.  Its job is to produce stable JSON
contracts that a future continuation model can consume:

``nodes``
    atomic text/visual fragments after v8 reading-order repair.

``candidate_edges``
    forward continuation candidates with geometry/text features only.

``labels``
    optional sidecar generated by the labeler, kept out of the graph input.
"""

from __future__ import annotations

from dataclasses import dataclass, field
