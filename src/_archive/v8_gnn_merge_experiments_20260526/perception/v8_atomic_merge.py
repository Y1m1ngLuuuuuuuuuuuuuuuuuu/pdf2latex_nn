def build_v8_atomic_merge_payload(
    *,
    doc_id: str,
    middle_json_path: Path,
    content_list_json_path: Path | None = None,
    style_content_list_json_path: Path | None = None,
    middle_block_source: str = "preproc_blocks",
    candidate_window: int = 4,
) -> dict[str, Any]:
    blocks = load_and_order_v8_blocks(
        doc_id=doc_id,
        middle_json_path=middle_json_path,
        content_list_json_path=content_list_json_path,
        style_content_list_json_path=style_content_list_json_path,
        middle_block_source=middle_block_source,
    )
    nodes = build_atomic_nodes(blocks)
    edges = build_candidate_edges(nodes, candidate_window=candidate_window)
    deterministic_payload = build_v8_from_middle(
        doc_id=doc_id,
        middle_json_path=middle_json_path,
        content_list_json_path=content_list_json_path,
        style_content_list_json_path=style_content_list_json_path,
        middle_block_source=middle_block_source,
    )
    deterministic_merges = deterministic_payload.get("merge_decisions") or []
    return {
        "schema_version": "v8_atomic_merge_graph_view_v1_2",
        "doc_id": doc_id,
        "source": {
            "middle_json": str(middle_json_path),
            "content_list_json": str(content_list_json_path) if content_list_json_path else None,
            "style_content_list_json": str(style_content_list_json_path) if style_content_list_json_path else None,
            "middle_block_source": middle_block_source,
        },
        "config": {
            "candidate_window": candidate_window,
            "input_leakage_policy": "nodes_and_edges_do_not_include_merge_labels",
        },
        "nodes": [node.to_json() for node in nodes],
        "candidate_edges": [edge.to_json() for edge in edges],
        "deterministic_merge_sidecar": deterministic_merges,
        "summary": summarize_atomic_payload(nodes, edges, deterministic_merges),
    }


def load_and_order_v8_blocks(
    *,
    doc_id: str,
    middle_json_path: Path,
    content_list_json_path: Path | None,
    style_content_list_json_path: Path | None,
    middle_block_source: str,
) -> list[V8Block]:
    payload = load_json(middle_json_path)
    blocks = extract_atomic_blocks(payload, doc_id=doc_id, source=middle_block_source)
    if content_list_json_path is not None:
        augment_blocks_from_content_list(blocks, load_json(content_list_json_path), content_list_json_path=content_list_json_path)
    if style_content_list_json_path is not None:
        attach_styles_from_content_list(
            blocks,
            load_json(style_content_list_json_path),
            style_content_list_json_path=style_content_list_json_path,
        )
    assign_layout_columns(blocks)
    return rebuild_reading_order(blocks)


def build_atomic_nodes(blocks: list[V8Block]) -> list[AtomicNode]:
    nodes: list[AtomicNode] = []
    for block in blocks:
        channel = classify_atomic_channel(block.type, block.text, page_idx=block.page_idx, metadata=block.metadata)
        if block.lines and block.type in TEXT_LIKE_TYPES:
            for line in block.lines:
                text = normalize_space(line.text)
                if not text:
                    continue
                line_channel = classify_atomic_channel(block.type, text, page_idx=block.page_idx, metadata=block.metadata)
                nodes.append(
                    AtomicNode(
                        atomic_id=f"a{len(nodes):07d}",
                        doc_id=block.doc_id,
                        text=text,
                        channel=line_channel,
                        raw_type=block.type,
                        page_idx=line.page_idx,
                        bbox=line.bbox or block.bbox,
                        page_size=block.page_size,
                        reading_order=len(nodes),
                        block_reading_order=block.reading_order,
                        source_middle_block_id=block.block_id,
                        source_line_id=line.line_id,
                        line_index=line.line_idx,
                        span_index=line.span_idx,
                        column_id=block.column_id,
                        is_full_width=block.is_full_width,
                        source_content_list_index=as_optional_int(block.metadata.get("source_content_list_index")),
                        style_content_list_index=as_optional_int(block.metadata.get("style_content_list_index")),
                        metadata=atomic_metadata_from_block(block),
                    )
                )
            continue
        nodes.append(
            AtomicNode(
                atomic_id=f"a{len(nodes):07d}",
                doc_id=block.doc_id,
                text=normalize_space(block.text),
                channel=channel,
                raw_type=block.type,
                page_idx=block.page_idx,
                bbox=block.bbox,
                page_size=block.page_size,
                reading_order=len(nodes),
                block_reading_order=block.reading_order,
                source_middle_block_id=block.block_id,
                source_line_id=None,
                line_index=None,
                span_index=None,
                column_id=block.column_id,
                is_full_width=block.is_full_width,
                source_content_list_index=as_optional_int(block.metadata.get("source_content_list_index")),
                style_content_list_index=as_optional_int(block.metadata.get("style_content_list_index")),
                metadata=atomic_metadata_from_block(block),
            )
        )
    return nodes


def build_candidate_edges(nodes: list[AtomicNode], *, candidate_window: int) -> list[AtomicCandidateEdge]:
    edges: list[AtomicCandidateEdge] = []
    mergeable_indices = [idx for idx, node in enumerate(nodes) if node.channel in MERGEABLE_CHANNELS and node.text]
    seen: set[tuple[str, str]] = set()

    for pos, src_idx in enumerate(mergeable_indices):
        src = nodes[src_idx]
        candidate_count = 0
        for dst_idx in mergeable_indices[pos + 1 :]:
            if candidate_count >= candidate_window:
                break
            dst = nodes[dst_idx]
            if dst.reading_order <= src.reading_order:
                continue
            skipped = nodes[src_idx + 1 : dst_idx]
            if too_far_for_candidate(src, dst, skipped):
                break
            key = (src.atomic_id, dst.atomic_id)
            if key in seen:
                continue
            seen.add(key)
            candidate_count += 1
            edge = make_candidate_edge(src, dst, skipped, edge_index=len(edges))
            edge.features.update(local_window_context_features(nodes, src_idx=src_idx, dst_idx=dst_idx))
            edges.append(edge)
    return edges


def make_candidate_edge(
    src: AtomicNode,
    dst: AtomicNode,
    skipped: list[AtomicNode],
    *,
    edge_index: int,
) -> AtomicCandidateEdge:
    page_delta = dst.page_idx - src.page_idx
    same_page = page_delta == 0
    same_column = same_page and src.column_id == dst.column_id
    layout_scope = classify_layout_scope(src, dst, skipped)
    vertical = vertical_gap(src, dst)
    overlap = x_overlap_ratio(src.bbox, dst.bbox)
    skipped_channels = [node.channel for node in skipped]
    src_tail = tail_text(src.text)
    dst_head = head_text(dst.text)
    features = {
        "src_open_ended": is_open_ended(src.text),
        "src_hyphen_ended": src.text.rstrip().endswith("-"),
        "src_comma_ended": normalize_space(src.text).rstrip().endswith(","),
        "src_alpha_ended": bool(ALPHA_END_RE.search(normalize_space(src.text).rstrip("- "))),
        "src_tail_hard_terminal": tail_ends_hard_terminal(src.text),
        "src_tail_soft_punctuation": tail_ends_soft_punctuation(src.text),
        "src_tail_abbrev_like": tail_abbrev_like(src.text),
        "src_tail_citation_closed": tail_citation_closed(src.text),
        "dst_tail_hard_terminal": tail_ends_hard_terminal(dst.text),
        "dst_tail_soft_punctuation": tail_ends_soft_punctuation(dst.text),
        "src_unclosed_parenthesis": has_unclosed_pair(src.text, "(", ")"),
        "src_unclosed_bracket": has_unclosed_pair(src.text, "[", "]") or has_unclosed_pair(src.text, "{", "}"),
        "src_unclosed_quote": has_unclosed_quote(src.text),
        "src_tail_after_math_symbol": tail_after_math_symbol(src.text),
        "src_tail_last_token_stopword": last_token_is_stopword(src.text),
        "dst_head_first_token_stopword": first_token_is_stopword(dst.text),
        "dst_starts_punctuation": starts_punctuation(dst.text),
        "dst_starts_closing_bracket": starts_closing_bracket(dst.text),
        "dst_head_conjunction": starts_with_conjunction(dst.text),
        "dst_head_preposition": starts_with_preposition(dst.text),
        "dst_lowercase_start": starts_lowercase(dst.text),
        "dst_uppercase_start": starts_uppercase(dst.text),
        "dst_parenthetical_start": normalize_space(dst.text).lstrip().startswith("("),
        "dst_continuation_word_start": starts_with_continuation_word(dst.text),
        "column_transition_type": classify_column_transition(src, dst),
        "src_near_column_bottom": is_near_page_bottom(src),
        "dst_near_column_top": is_near_page_top(dst),
        "same_column_flow_lane": same_page and same_column and vertical is not None and vertical >= -2.0,
        "skipped_float_count": sum(1 for value in skipped_channels if value == "FLOAT_PROXY"),
        "skipped_formula_count": sum(1 for value in skipped_channels if value == "DISPLAY_MATH"),
        "skipped_caption_count": sum(1 for value in skipped_channels if value == "CAPTION"),
        "skipped_heading_count": sum(1 for value in skipped_channels if value == "HEADING"),
        "skipped_barrier_count": sum(1 for value in skipped_channels if value in BARRIER_CHANNELS),
        "skipped_figure_count": sum(1 for node in skipped if str(node.raw_type).lower() in FLOAT_RAW_TYPES),
        "skipped_table_count": sum(1 for node in skipped if str(node.raw_type).lower() in TABLE_RAW_TYPES),
        "skipped_algorithm_count": sum(1 for node in skipped if str(node.raw_type).lower() in ALGORITHM_RAW_TYPES),
        "skipped_code_count": sum(1 for node in skipped if str(node.raw_type).lower() in CODE_RAW_TYPES),
        "skipped_wide_float_count": count_wide_skipped_floats(skipped, min_width_ratio=0.62),
        "skipped_full_width_float_count": sum(1 for node in skipped if node.channel == "FLOAT_PROXY" and node.is_full_width),
        "skipped_max_float_width_ratio": max_float_width_ratio(skipped),
        "skipped_has_caption": any(node.channel == "CAPTION" for node in skipped),
        "skipped_display_math_between": any(node.channel == "DISPLAY_MATH" for node in skipped),
        "src_before_float_dst_after_float": src.channel in {"BODY_TEXT", "LIST_ITEM"} and dst.channel in {"BODY_TEXT", "LIST_ITEM"} and any(node.channel == "FLOAT_PROXY" for node in skipped),
    }
    return AtomicCandidateEdge(
        edge_id=f"e{edge_index:08d}",
        src_atomic_id=src.atomic_id,
        dst_atomic_id=dst.atomic_id,
        src_channel=src.channel,
        dst_channel=dst.channel,
        candidate_family=candidate_family(src, dst, skipped, layout_scope),
        reading_order_gap=dst.reading_order - src.reading_order,
        page_delta=page_delta,
        same_page=same_page,
        same_column=same_column,
        layout_scope=layout_scope,
        vertical_gap=vertical,
        x_overlap_ratio=overlap,
        skipped_node_ids=[node.atomic_id for node in skipped],
        skipped_channels=skipped_channels,
        src_tail=src_tail,
        dst_head=dst_head,
        pair_text=f"{src_tail} [SEP] {dst_head}",
        features=features,
    )


def local_window_context_features(nodes: list[AtomicNode], *, src_idx: int, dst_idx: int) -> dict[str, Any]:
    """Summarize a tiny local window without exposing merge-owner labels.

    These are intentionally coarse context features for the optional atomic
    MERGE branch.  They do not include middle/content owner equality.
    """

    src_prev2 = nodes[max(0, src_idx - 2) : src_idx]
    src_next2 = nodes[src_idx + 1 : min(len(nodes), src_idx + 3)]
    dst_prev2 = nodes[max(0, dst_idx - 2) : dst_idx]
    dst_next2 = nodes[dst_idx + 1 : min(len(nodes), dst_idx + 3)]
    return {
        **_window_prefix_features("src_prev2", src_prev2),
        **_window_prefix_features("src_next2", src_next2),
        **_window_prefix_features("dst_prev2", dst_prev2),
        **_window_prefix_features("dst_next2", dst_next2),
        **_adjacent_gap_features("src", nodes, src_idx),
        **_adjacent_gap_features("dst", nodes, dst_idx),
        "candidate_gap_vs_src_next_gap": gap_ratio_against_adjacent(nodes[src_idx], nodes[dst_idx], nodes, src_idx, direction="next"),
        "candidate_gap_vs_dst_prev_gap": gap_ratio_against_adjacent(nodes[src_idx], nodes[dst_idx], nodes, dst_idx, direction="prev"),
        "between_node_count": max(0, dst_idx - src_idx - 1),
        "between_body_text_count": sum(1 for node in nodes[src_idx + 1 : dst_idx] if node.channel == "BODY_TEXT"),
        "between_list_count": sum(1 for node in nodes[src_idx + 1 : dst_idx] if node.channel == "LIST_ITEM"),
        "between_barrier_count": sum(1 for node in nodes[src_idx + 1 : dst_idx] if node.channel in BARRIER_CHANNELS),
    }


def _window_prefix_features(prefix: str, window: list[AtomicNode]) -> dict[str, Any]:
    return {
        f"{prefix}_body_text_count": sum(1 for node in window if node.channel == "BODY_TEXT"),
        f"{prefix}_list_count": sum(1 for node in window if node.channel == "LIST_ITEM"),
        f"{prefix}_heading_count": sum(1 for node in window if node.channel == "HEADING"),
        f"{prefix}_formula_count": sum(1 for node in window if node.channel == "DISPLAY_MATH"),
        f"{prefix}_float_count": sum(1 for node in window if node.channel == "FLOAT_PROXY"),
        f"{prefix}_caption_count": sum(1 for node in window if node.channel == "CAPTION"),
        f"{prefix}_reference_count": sum(1 for node in window if node.channel == "REFERENCE_ITEM"),
        f"{prefix}_front_matter_count": sum(1 for node in window if node.channel == "FRONT_MATTER"),
    }


def _adjacent_gap_features(prefix: str, nodes: list[AtomicNode], index: int) -> dict[str, Any]:
    node = nodes[index]
    prev_gap = adjacent_vertical_gap(nodes[index - 1], node) if index > 0 else None
    next_gap = adjacent_vertical_gap(node, nodes[index + 1]) if index + 1 < len(nodes) else None
    line_height = max(1.0, bbox_height(node.bbox))
    return {
        f"{prefix}_prev_gap": prev_gap,
        f"{prefix}_next_gap": next_gap,
        f"{prefix}_prev_gap_by_line_height": safe_gap_ratio(prev_gap, line_height),
        f"{prefix}_next_gap_by_line_height": safe_gap_ratio(next_gap, line_height),
    }


def classify_atomic_channel(raw_type: Any, text: str, *, page_idx: int, metadata: dict[str, Any]) -> str:
    block_type = normalize_content_type(raw_type)
    role = str(metadata.get("layout_role") or metadata.get("content_list_type") or "").casefold()
    value = normalize_space(text)
    lowered = value.casefold()
    if role in {"page_header", "page_footer", "page_number", "header", "footer"}:
        return "PAGE_FURNITURE"
    if page_idx == 0 and (EMAIL_RE.search(value) or AFFILIATION_RE.search(value)):
        return "FRONT_MATTER"
    if block_type == "title":
        return "HEADING"
    if CAPTION_PREFIX_RE.search(value):
        return "CAPTION"
    if block_type in {"equation", "interline_equation", "equation_interline", "display_formula", "formula"}:
        return "DISPLAY_MATH"
    if block_type in {"table", "figure", "image", "chart", "algorithm", "code"}:
        return "FLOAT_PROXY"
    if block_type in {"list", "list_item"} or re.match(r"^\s*(?:[-*•]|\d+[.)])\s+", value):
        return "LIST_ITEM"
    if block_type in {"ref_text", "reference"} or REFERENCE_PREFIX_RE.search(value):
        return "REFERENCE_ITEM"
    if block_type in {"text", "paragraph", "abstract"}:
        if lowered.strip(" .:") == "abstract" and page_idx == 0:
            return "FRONT_MATTER"
        return "BODY_TEXT"
    return "UNKNOWN"


def candidate_family(src: AtomicNode, dst: AtomicNode, skipped: list[AtomicNode], layout_scope: str) -> str:
    if src.channel == "LIST_ITEM" and dst.channel == "LIST_ITEM":
        return "LIST_CONTINUATION"
    if src.channel == "REFERENCE_ITEM" and dst.channel == "REFERENCE_ITEM":
        return "REFERENCE_CONTINUATION"
    if src.channel == "BODY_TEXT" and dst.channel == "BODY_TEXT":
        skipped_channels = {node.channel for node in skipped}
        if "DISPLAY_MATH" in skipped_channels:
            return "FORMULA_CONTEXT"
        if "FLOAT_PROXY" in skipped_channels:
            return "FLOAT_SKIP_CONTINUATION"
        if layout_scope == "layout_scope_mismatch":
            return "LAYOUT_SCOPE_MISMATCH"
        return "BODY_TEXT_CONTINUATION"
    return "MASKED_UNKNOWN"


def classify_layout_scope(src: AtomicNode, dst: AtomicNode, skipped: list[AtomicNode]) -> str:
    if src.page_idx == dst.page_idx and src.column_id == dst.column_id:
        return "same_column"
    if src.page_idx == dst.page_idx and src.column_id in {0, 1} and dst.column_id in {0, 1}:
        if all(node.channel == "FLOAT_PROXY" for node in skipped if node.channel != "PAGE_FURNITURE"):
            return "skip_over_float"
        return "layout_scope_mismatch"
    if dst.page_idx == src.page_idx + 1:
        return "cross_page"
    return "layout_scope_mismatch"


def classify_column_transition(src: AtomicNode, dst: AtomicNode) -> str:
    if src.page_idx == dst.page_idx and src.column_id == dst.column_id:
        return "same_column_down"
    if src.page_idx == dst.page_idx and src.column_id == 0 and dst.column_id == 1:
        return "left_to_right_column"
    if dst.page_idx == src.page_idx + 1 and src.column_id == 1 and dst.column_id in {0, None}:
        return "right_to_next_page_left"
    if dst.page_idx == src.page_idx + 1 and src.column_id == dst.column_id:
        return "cross_page_same_column"
    if dst.page_idx == src.page_idx + 1:
        return "cross_page_column_reset"
    return "other"


def too_far_for_candidate(src: AtomicNode, dst: AtomicNode, skipped: list[AtomicNode]) -> bool:
    if dst.page_idx > src.page_idx + 1:
        return True
    if dst.page_idx == src.page_idx and len(skipped) > 16:
        return True
    if dst.page_idx == src.page_idx + 1 and src.page_size and src.bbox and src.bbox[3] < src.page_size[1] * 0.55:
        return True
    return False


def summarize_atomic_payload(
    nodes: list[AtomicNode],
    edges: list[AtomicCandidateEdge],
    deterministic_merges: list[Any],
) -> dict[str, Any]:
    return {
        "node_count": len(nodes),
        "candidate_edge_count": len(edges),
        "deterministic_merge_count": len(deterministic_merges),
        "channel_counts": count_values(node.channel for node in nodes),
        "candidate_family_counts": count_values(edge.candidate_family for edge in edges),
    }


def atomic_metadata_from_block(block: V8Block) -> dict[str, Any]:
    keep = {}
    for key in (
        "source_content_list_index",
        "content_list_type",
        "content_list_match_score",
        "style_content_list_index",
        "style_content_list_match_score",
        "font_size",
        "bold_ratio",
        "relative_font_size",
    ):
        if key in block.metadata:
            keep[key] = block.metadata[key]
    return keep


def vertical_gap(src: AtomicNode, dst: AtomicNode) -> float | None:
    if not src.bbox or not dst.bbox or len(src.bbox) != 4 or len(dst.bbox) != 4:
        return None
    return float(dst.bbox[1] - src.bbox[3])


def adjacent_vertical_gap(src: AtomicNode, dst: AtomicNode) -> float | None:
    if src.page_idx != dst.page_idx or src.column_id != dst.column_id:
        return None
    return vertical_gap(src, dst)


def bbox_height(bbox: list[float]) -> float:
    if len(bbox) != 4:
        return 0.0
    return max(0.0, float(bbox[3]) - float(bbox[1]))


def safe_gap_ratio(gap: float | None, denom: float) -> float | None:
    if gap is None:
        return None
    return float(gap) / max(1.0, float(denom))


def gap_ratio_against_adjacent(
    src: AtomicNode,
    dst: AtomicNode,
    nodes: list[AtomicNode],
    index: int,
    *,
    direction: str,
) -> float | None:
    candidate_gap = adjacent_vertical_gap(src, dst)
    if candidate_gap is None:
        return None
    if direction == "next" and index + 1 < len(nodes):
        reference = adjacent_vertical_gap(nodes[index], nodes[index + 1])
    elif direction == "prev" and index > 0:
        reference = adjacent_vertical_gap(nodes[index - 1], nodes[index])
    else:
        reference = None
    if reference is None:
        return None
    return float(candidate_gap) / max(1.0, abs(float(reference)))


def x_overlap_ratio(a: list[float], b: list[float]) -> float | None:
    if len(a) != 4 or len(b) != 4:
        return None
    overlap = max(0.0, min(a[2], b[2]) - max(a[0], b[0]))
    denom = max(1.0, min(max(0.0, a[2] - a[0]), max(0.0, b[2] - b[0])))
    return overlap / denom


def is_open_ended(text: str) -> bool:
    value = normalize_space(text)
    if not value:
        return False
    if value.endswith("-"):
        return True
    if tail_ends_soft_punctuation(value):
        return True
    if tail_abbrev_like(value):
        return True
    return not bool(OPEN_SENTENCE_RE.search(value))


def tail_ends_hard_terminal(text: str) -> bool:
    """True for sentence-final punctuation, excluding common abbreviations."""

    value = normalize_space(text)
    if not value or not HARD_TERMINAL_RE.search(value):
        return False
    return not tail_abbrev_like(value)


def tail_ends_soft_punctuation(text: str) -> bool:
    """True for punctuation that often means continuation rather than closure."""

    return bool(SOFT_CONTINUATION_RE.search(normalize_space(text)))


def tail_abbrev_like(text: str) -> bool:
    return bool(ABBREV_TAIL_RE.search(normalize_space(text).rstrip()))


def tail_citation_closed(text: str) -> bool:
    return bool(CITATION_CLOSED_RE.search(normalize_space(text).rstrip()))


def has_unclosed_pair(text: str, left: str, right: str) -> bool:
    value = normalize_space(text)
    return value.count(left) > value.count(right)


def has_unclosed_quote(text: str) -> bool:
    value = normalize_space(text)
    quote_count = value.count('"') + value.count("“") + value.count("”")
    single_quote_count = len(re.findall(r"(?<![A-Za-z])'(?![A-Za-z])", value))
    return bool(quote_count % 2 or single_quote_count % 2)


def tail_after_math_symbol(text: str) -> bool:
    return bool(MATH_TAIL_RE.search(normalize_space(text).rstrip()))


def starts_punctuation(text: str) -> bool:
    return bool(PUNCT_START_RE.search(normalize_space(text).lstrip()))


def starts_closing_bracket(text: str) -> bool:
    return bool(CLOSING_BRACKET_START_RE.search(normalize_space(text).lstrip()))


def first_token(text: str) -> str:
    match = TOKEN_RE.search(normalize_space(text))
    return match.group(0).casefold() if match else ""


def last_token(text: str) -> str:
    matches = TOKEN_RE.findall(normalize_space(text))
    return matches[-1].casefold() if matches else ""


def first_token_is_stopword(text: str) -> bool:
    return first_token(text) in STOPWORDS


def last_token_is_stopword(text: str) -> bool:
    return last_token(text) in STOPWORDS


def starts_lowercase(text: str) -> bool:
    return bool(LOWER_START_RE.search(normalize_space(text).lstrip("([{")))


def starts_uppercase(text: str) -> bool:
    return bool(UPPER_START_RE.search(normalize_space(text).lstrip("([{")))


def starts_with_continuation_word(text: str) -> bool:
    value = normalize_space(text).lstrip("([{").casefold()
    return bool(re.match(r"^(and|or|but|for|to|of|in|on|with|which|where|while|because|that|than|from|as|by)\b", value))


def starts_with_conjunction(text: str) -> bool:
    return bool(CONJUNCTION_START_RE.match(normalize_space(text).lstrip("([{").casefold()))


def starts_with_preposition(text: str) -> bool:
    return bool(PREPOSITION_START_RE.match(normalize_space(text).lstrip("([{").casefold()))


def is_near_page_bottom(node: AtomicNode, threshold: float = 0.82) -> bool:
    if not node.bbox or not node.page_size or len(node.bbox) != 4 or len(node.page_size) < 2:
        return False
    return float(node.bbox[3]) / max(1.0, float(node.page_size[1])) >= threshold


def is_near_page_top(node: AtomicNode, threshold: float = 0.18) -> bool:
    if not node.bbox or not node.page_size or len(node.bbox) != 4 or len(node.page_size) < 2:
        return False
    return float(node.bbox[1]) / max(1.0, float(node.page_size[1])) <= threshold


def max_float_width_ratio(nodes: list[AtomicNode]) -> float:
    ratios = [float_width_ratio(node) for node in nodes if node.channel == "FLOAT_PROXY"]
    return max(ratios) if ratios else 0.0


def count_wide_skipped_floats(nodes: list[AtomicNode], *, min_width_ratio: float) -> int:
    return sum(1 for node in nodes if node.channel == "FLOAT_PROXY" and float_width_ratio(node) >= min_width_ratio)


def float_width_ratio(node: AtomicNode) -> float:
    if not node.bbox or not node.page_size or len(node.bbox) != 4 or len(node.page_size) < 1:
        return 0.0
    width = max(0.0, float(node.bbox[2]) - float(node.bbox[0]))
    return max(0.0, min(width / max(1.0, float(node.page_size[0])), 1.0))


def head_text(text: str, limit: int = 160) -> str:
    return normalize_space(text)[:limit]


def tail_text(text: str, limit: int = 160) -> str:
    value = normalize_space(text)
    return value[-limit:]


def count_values(values: Any) -> dict[str, int]:
    counts: dict[str, int] = {}
    for value in values:
        key = str(value)
        counts[key] = counts.get(key, 0) + 1
    return dict(sorted(counts.items()))


def as_optional_int(value: Any) -> int | None:
    try:
        if value is None:
            return None
        return int(value)
    except (TypeError, ValueError):
        return None
